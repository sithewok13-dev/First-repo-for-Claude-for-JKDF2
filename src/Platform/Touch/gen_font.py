#!/usr/bin/env python3
# Makes touchUiFont.h: the touch overlay's label font as a signed distance
# field atlas (printable ASCII), so the GL renderer draws crisp text at any
# size from one small texture, before any game data has loaded.
#
# Font: Liberation Sans Bold (SIL Open Font License 1.1; Debian/Ubuntu
# package fonts-liberation). Only the rendered distance field is kept.
#
# usage: python3 gen_font.py [path/to/LiberationSans-Bold.ttf] > touchUiFont.h
import sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"
EM = 32          # atlas pixels per em
HI = 8           # supersampling of the outlines the distances are measured on
SPREAD = 4.0     # atlas pixels of distance either side of the edge
PAD = 5          # atlas pixels round each glyph
ATLAS_W = 512

font = ImageFont.truetype(TTF, EM * HI)
ascent, descent = font.getmetrics()

def sdf_for(ch):
    l, t, r, b = font.getbbox(ch, anchor="ls")  # relative to the baseline's left end
    adv = font.getlength(ch) / HI
    if r <= l or b <= t:
        return None, adv
    # the glyph's cell, in whole atlas pixels, PAD round its ink
    x0 = int(np.floor(l / HI)) - PAD
    y0 = int(np.floor(t / HI)) - PAD
    x1 = int(np.ceil(r / HI)) + PAD
    y1 = int(np.ceil(b / HI)) + PAD
    w, h = x1 - x0, y1 - y0
    img = Image.new("L", (w * HI, h * HI), 0)
    ImageDraw.Draw(img).text((-x0 * HI, -y0 * HI), ch, font=font, fill=255, anchor="ls")
    m = np.asarray(img) >= 128
    # the edge: inside pixels with an outside neighbour, and the other way round
    inside = m
    edge = np.zeros_like(m)
    edge[1:, :] |= m[1:, :] != m[:-1, :]
    edge[:-1, :] |= m[1:, :] != m[:-1, :]
    edge[:, 1:] |= m[:, 1:] != m[:, :-1]
    edge[:, :-1] |= m[:, 1:] != m[:, :-1]
    ey, ex = np.nonzero(edge)
    ex = ex.astype(np.float32) + 0.5
    ey = ey.astype(np.float32) + 0.5
    out = np.zeros((h, w), dtype=np.uint8)
    sy, sx = np.mgrid[0:h, 0:w]
    px = (sx.astype(np.float32) + 0.5) * HI
    py = (sy.astype(np.float32) + 0.5) * HI
    px = px.ravel(); py = py.ravel()
    best = np.full(px.shape, 1e9, dtype=np.float32)
    CH = 4096
    for i in range(0, len(ex), CH):
        dx = px[:, None] - ex[None, i:i + CH]
        dy = py[:, None] - ey[None, i:i + CH]
        best = np.minimum(best, np.sqrt(dx * dx + dy * dy).min(axis=1))
    d = best / HI  # atlas pixels
    sign = np.where(inside[(py - 0.5).astype(int).clip(0, h * HI - 1), (px - 0.5).astype(int).clip(0, w * HI - 1)], 1.0, -1.0)
    v = 128.0 + sign * d * (127.0 / SPREAD)
    out = np.clip(np.round(v), 0, 255).astype(np.uint8).reshape(h, w)
    return (out, x0, y0), adv

glyphs = {}
for c in range(32, 127):
    g, adv = sdf_for(chr(c))
    glyphs[c] = (g, adv)

# Pack into rows
x = y = rowh = 0
places = {}
for c in range(32, 127):
    g, adv = glyphs[c]
    if g is None:
        places[c] = None
        continue
    arr = g[0]
    h, w = arr.shape
    if x + w > ATLAS_W:
        x = 0; y += rowh + 1; rowh = 0
    places[c] = (x, y)
    x += w + 1
    rowh = max(rowh, h)
ATLAS_H = y + rowh
ATLAS_H = (ATLAS_H + 3) // 4 * 4
atlas = np.zeros((ATLAS_H, ATLAS_W), dtype=np.uint8)
for c in range(32, 127):
    g, adv = glyphs[c]
    if g is None:
        continue
    arr = g[0]
    h, w = arr.shape
    px, py = places[c]
    atlas[py:py + h, px:px + w] = arr

capl, capt, capr, capb = font.getbbox("H", anchor="ls")
o = []
o.append("// Generated by gen_font.py: do not edit. The touch overlay's label font:")
o.append("// Liberation Sans Bold (SIL Open Font License 1.1), as a signed distance")
o.append("// field atlas of printable ASCII. 128 is the outline; each step of")
o.append("// 127/SPREAD is one atlas pixel inside (up) or outside (down).")
o.append("#ifndef TOUCHUI_FONT_H")
o.append("#define TOUCHUI_FONT_H")
o.append("#define TOUCHUI_FONT_EM %d" % EM)
o.append("#define TOUCHUI_FONT_SPREAD %.1ff" % SPREAD)
o.append("#define TOUCHUI_FONT_ASCENT %.3ff" % (ascent / HI))
o.append("#define TOUCHUI_FONT_DESCENT %.3ff" % (descent / HI))
o.append("#define TOUCHUI_FONT_CAP %.3ff" % (-capt / HI))
o.append("#define TOUCHUI_FONT_ATLAS_W %d" % ATLAS_W)
o.append("#define TOUCHUI_FONT_ATLAS_H %d" % ATLAS_H)
o.append("typedef struct { short x, y, w, h, ox, oy; float adv; } touchUiGlyph; // ox, oy: the cell's top left from the pen on the baseline")
o.append("static const touchUiGlyph touchUiFont_aGlyphs[95] = {")
for c in range(32, 127):
    g, adv = glyphs[c]
    if g is None:
        o.append("    { 0, 0, 0, 0, 0, 0, %.3ff }, // %r" % (adv, chr(c)))
    else:
        arr, x0, y0 = g
        h, w = arr.shape
        px, py = places[c]
        o.append("    { %d, %d, %d, %d, %d, %d, %.3ff }, // %s" % (px, py, w, h, x0, y0, adv, repr(chr(c)).replace("\\", "\\\\")))
o.append("};")
o.append("#ifdef TOUCHUI_FONT_ATLAS")
o.append("static const unsigned char touchUiFont_aAtlas[%d] = {" % (ATLAS_W * ATLAS_H))
flat = atlas.ravel()
for i in range(0, len(flat), 32):
    o.append(",".join(str(int(v)) for v in flat[i:i + 32]) + ",")
o.append("};")
o.append("#endif")
o.append("#endif")
print("\n".join(o))
