def tile(rows):
    lo = []
    for r in rows + ["     "]:
        bits = 0
        for i, ch in enumerate(r.ljust(8)):
            if ch == '#':
                bits |= 0x80 >> (i + 1)  # 1px left margin
        lo.append(bits)
    return bytes(lo) + bytes(8)  # color 1 only (plane 0)

chr_data = bytearray(8192)
for ch, rows in GLYPHS.items():
    assert len(rows) == 7, ch
    idx = ord(ch)
    chr_data[idx*16:idx*16+16] = tile(rows)
# tile $80: solid block in color 1 (the player colour)
chr_data[0x80*16:0x80*16+16] = bytes([0xFF]*8 + [0x00]*8)
sys.stdout.buffer.write(chr_data)
